-- =============================================================
--  第 2 章 · 关系代数 ↔ SQL 对照练习
--  左侧注释是关系代数表达式，下面是对应的 SQL。
--  全部基于教材样例库 dbs_course（Student / Course / SC）。
--  运行：./scripts/db.sh < "sql/ch02-关系数据库/关系代数.sql"
-- =============================================================

USE dbs_course;
SET NAMES utf8mb4;

-- ------------------------------------------------------------
-- 1. 选择：σ_{Sdept='CS'}(Student)
--    取「行」——挑出符合条件的元组
-- ------------------------------------------------------------
SELECT * FROM Student WHERE Sdept = 'CS';

-- ------------------------------------------------------------
-- 2. 投影：π_{Sname,Sdept}(Student)
--    取「列」，关系代数里自动去重
-- ------------------------------------------------------------
SELECT DISTINCT Sname, Sdept FROM Student;

-- ------------------------------------------------------------
-- 3. 选择 + 投影：π_{Sname}(σ_{Sage<20}(Student))
--    先挑行再挑列（顺序可以换，代价不同）
-- ------------------------------------------------------------
SELECT Sname FROM Student WHERE Sage < 20;

-- ------------------------------------------------------------
-- 4. π_{Sno}(σ_{Cno='1'}(SC)) —— 选了 1 号课的学生学号
-- ------------------------------------------------------------
SELECT DISTINCT Sno FROM SC WHERE Cno = '1';

-- ------------------------------------------------------------
-- 5. Student ⋈ SC —— 自然连接（等值连接去掉重复属性）
-- ------------------------------------------------------------
SELECT * FROM Student NATURAL JOIN SC;

-- ------------------------------------------------------------
-- 6. π_{Sname}(σ_{Cno='1'}(Student ⋈ SC))
--    选了 1 号课的学生的姓名：连接 → 选择 → 投影
-- ------------------------------------------------------------
SELECT S.Sname
FROM Student S
JOIN SC ON S.Sno = SC.Sno
WHERE SC.Cno = '1';

-- ------------------------------------------------------------
-- 7. 差运算：π_{Sno}(Student) − π_{Sno}(SC)
--    一门课都没选的学生
-- ------------------------------------------------------------
SELECT Sno FROM Student
EXCEPT
SELECT Sno FROM SC;

-- ------------------------------------------------------------
-- 8. 并运算：选了 1 号课 或 3 号课的学生
--    ∪ 在 SQL 里是 UNION（自动去重），UNION ALL 保留重复
-- ------------------------------------------------------------
SELECT Sno FROM SC WHERE Cno = '1'
UNION
SELECT Sno FROM SC WHERE Cno = '3';

-- ------------------------------------------------------------
-- 9. 交运算：选了 1 号课 并且 也选了 3 号课的学生
--    ∩ 不是基本运算，A∩B = A − (A − B)
-- ------------------------------------------------------------
SELECT Sno FROM SC WHERE Cno = '1'
INTERSECT
SELECT Sno FROM SC WHERE Cno = '3';

-- ------------------------------------------------------------
-- 10. 除法：选修了「全部」课程的学生
--     关系代数：π_{Sno,Cno}(SC) ÷ π_{Cno}(Course)
--     SQL 用双重 NOT EXISTS：不存在一门课，是他没选的
-- ------------------------------------------------------------
SELECT S.Sno, S.Sname
FROM Student S
WHERE NOT EXISTS (
        SELECT * FROM Course C
        WHERE NOT EXISTS (
                SELECT * FROM SC
                WHERE SC.Sno = S.Sno AND SC.Cno = C.Cno
        )
);

-- ------------------------------------------------------------
-- 11. 除法变体：选修了「刘晨」所选全部课程的学生
--     典型套路：把「刘晨选的课」当成全集
-- ------------------------------------------------------------
SELECT S.Sno, S.Sname
FROM Student S
WHERE NOT EXISTS (
        SELECT * FROM SC X
        WHERE X.Sno = '200215122'
          AND NOT EXISTS (
                SELECT * FROM SC Y
                WHERE Y.Sno = S.Sno AND Y.Cno = X.Cno
        )
);

-- ------------------------------------------------------------
-- 12. 聚集：教材里的「查询结果排序」
--     π_{Sdept}(Student) 只有 3 个系，这是集合语义的好处
-- ------------------------------------------------------------
SELECT Sdept AS 系, COUNT(*) AS 人数
FROM Student
GROUP BY Sdept
ORDER BY 人数 DESC;

-- ------------------------------------------------------------
-- 13. 年龄小于平均年龄的学生
--     关系代数没法直接表达聚集，说明关系代数还不够用，
--     这正是 SQL 要扩展出聚集函数的原因
-- ------------------------------------------------------------
SELECT Sname, Sage
FROM Student
WHERE Sage < (SELECT AVG(Sage) FROM Student);

-- ------------------------------------------------------------
-- 14. 自身连接：每个学生的年龄和「李勇」差多少
--     关系代数里就是同一张表和自己做笛卡尔积再选择
-- ------------------------------------------------------------
SELECT A.Sname AS 学生, A.Sage AS 年龄, A.Sage - B.Sage AS 与李勇的年龄差
FROM Student A, Student B
WHERE B.Sname = '李勇' AND A.Sname <> '李勇';

-- ------------------------------------------------------------
-- 15. 先修课：Course 自参照，π_{Cname,Cpno}
-- ------------------------------------------------------------
SELECT C1.Cname AS 课程, C2.Cname AS 先修课
FROM Course C1
LEFT JOIN Course C2 ON C1.Cpno = C2.Cno
ORDER BY C1.Cno;

