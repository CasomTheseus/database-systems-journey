-- 17. 用元数据看约束，比背概念直观
SELECT TABLE_NAME AS 表, CONSTRAINT_NAME AS 约束, CONSTRAINT_TYPE AS 类型
FROM information_schema.TABLE_CONSTRAINTS
WHERE TABLE_SCHEMA = 'dbs_course'
ORDER BY TABLE_NAME, CONSTRAINT_TYPE;
